import { createHash, randomInt, timingSafeEqual } from 'node:crypto';
import { hashPassword, verifyPassword } from './password.js';

/**
 * Numeric one-time codes and device fingerprints.
 */

/** A zero-padded decimal code drawn from a cryptographically secure source. */
export function generateCode(digits: number): string {
  const max = 10 ** digits;
  return String(randomInt(0, max)).padStart(digits, '0');
}

/**
 * Codes are hashed with the same function as passwords.
 *
 * That is deliberately expensive for a six-digit secret, but the cost is paid
 * once per attempt and the attempt count is capped at three — while a fast hash
 * would make a leaked database trivially brute-forceable.
 */
export const hashCode = hashPassword;

export const verifyCode = verifyPassword;

/**
 * Device identifiers are opaque random strings generated by the client. Only
 * their SHA-256 digest is stored, so reading the table does not reveal a value
 * that could be replayed as a trusted device.
 */
export function hashDevice(deviceId: string | undefined | null): string | null {
  const value = typeof deviceId === 'string' ? deviceId.trim() : '';
  if (value.length < 16 || value.length > 200) return null;

  return createHash('sha256').update(value).digest('hex');
}

/** Constant-time comparison for two hex digests of equal length. */
export function digestsMatch(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  return timingSafeEqual(Buffer.from(a, 'hex'), Buffer.from(b, 'hex'));
}

/**
 * Shortens an address for display: enough to tell the reader which mailbox to
 * open, not enough to hand a full address to whoever guessed the password.
 */
export function maskEmail(email: string): string {
  const [name = '', domain = ''] = email.split('@');
  if (!domain) return '';

  const head = name.slice(0, 2);
  const dot = domain.indexOf('.');
  const zone = dot === -1 ? '' : domain.slice(dot);

  return `${head}${'*'.repeat(Math.max(1, name.length - 2))}@${domain[0] ?? ''}***${zone}`;
}
